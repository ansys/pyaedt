class _OAnsoftApp(Protocol):
    """Interface definition for the AnsoftApp object."""

    objectID: int

    def GetAppDesktop(self) -> _ODesktop: ...


class _ODesktop(Protocol):
    """Interface definition for the AEDT desktop object."""

    def GetProcessID(self) -> int: ...
    def GetActiveProject(self) -> object: ...
    def GetMessages(self, *args, **kwargs) -> list[str]: ...
    def GetVersion(self) -> str: ...
    def NewProject(self, *args: object, **kwargs: object) -> _OProject: ...
    def SetActiveProject(self, *args, **kwargs) -> object: ...
    def CloseAllWindows(self) -> object: ...
    def CloseProject(self, *args: object, **kwargs: object) -> object: ...


